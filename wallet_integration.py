"""Carteira universal Ativa Gaming, integrada à conta existente.

Adicionar em main.py:
    from wallet_integration import router as wallet_router
    app.include_router(wallet_router)

Requer as mesmas variáveis DATABASE_URL e SESSION_SECRET já usadas pela Ativa Gaming.
"""

import os
import re
from datetime import datetime, timezone
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row
from fastapi import APIRouter, HTTPException, Request
from itsdangerous import URLSafeTimedSerializer, BadSignature
from pydantic import BaseModel, Field

DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = "postgresql://" + DATABASE_URL[len("postgres://"):]
SESSION_SECRET = os.environ.get("SESSION_SECRET", "").strip()
COOKIE_NAME = "ativa_session"

if not SESSION_SECRET:
    raise RuntimeError("Configure SESSION_SECRET nas variáveis Environment do Render.")

serializer = URLSafeTimedSerializer(SESSION_SECRET, salt="ativa-gaming-session")
router = APIRouter(tags=["Carteira Universal"])

# Preços são definidos exclusivamente no servidor. Nunca aceitar custo enviado pelo navegador.
# Adicione os itens dos demais jogos aqui, usando o ID oficial de cada jogo.
STORE_ITEMS = {
    ("ativa-strike", "uniforme_tatico"): {"name": "Uniforme Tático", "cost": 150},
    ("ativa-strike", "rifle_aurora"): {"name": "Rifle Aurora", "cost": 220},
    ("ativa-strike", "colete_reforcado"): {"name": "Colete Reforçado", "cost": 180},
    ("ativa-strike", "emblema_elite"): {"name": "Emblema Elite", "cost": 90},
}


def now_utc():
    return datetime.now(timezone.utc).isoformat()


@contextmanager
def db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL não configurada no ambiente do serviço.")
    connection = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_wallet_tables():
    """Cria tabelas novas sem apagar nem alterar os cadastros existentes."""
    with db() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS wallet_accounts (
                player_id BIGINT PRIMARY KEY REFERENCES players(id) ON DELETE CASCADE,
                balance BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0),
                updated_at TEXT NOT NULL
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS wallet_transactions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
                delta BIGINT NOT NULL,
                balance_after BIGINT NOT NULL CHECK (balance_after >= 0),
                reason TEXT NOT NULL,
                game_id TEXT,
                item_id TEXT,
                created_at TEXT NOT NULL
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS player_inventory (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
                game_id TEXT NOT NULL,
                item_id TEXT NOT NULL,
                item_name TEXT NOT NULL,
                purchased_at TEXT NOT NULL,
                UNIQUE (player_id, game_id, item_id)
            )
        """)


# Cria apenas tabelas novas; não modifica nem remove players/scores.
init_wallet_tables()


def authenticated_player(request: Request):
    token = request.cookies.get(COOKIE_NAME)
    if not token:
        raise HTTPException(status_code=401, detail="Entre na sua conta Ativa Gaming primeiro.")
    try:
        data = serializer.loads(token, max_age=60 * 60 * 24 * 7)
        player_id = int(data["player_id"])
    except (BadSignature, ValueError, KeyError, TypeError):
        raise HTTPException(status_code=401, detail="Sessão inválida. Entre novamente.")

    with db() as connection:
        player = connection.execute(
            "SELECT id, username FROM players WHERE id = %s", (player_id,)
        ).fetchone()
    if not player:
        raise HTTPException(status_code=401, detail="Conta não encontrada. Entre novamente.")
    return dict(player)


def ensure_wallet(connection, player_id: int):
    connection.execute(
        "INSERT INTO wallet_accounts (player_id, balance, updated_at) VALUES (%s, 0, %s) ON CONFLICT (player_id) DO NOTHING",
        (player_id, now_utc()),
    )
    return connection.execute(
        "SELECT balance FROM wallet_accounts WHERE player_id = %s", (player_id,)
    ).fetchone()


class SpendInput(BaseModel):
    game_id: str = Field(min_length=2, max_length=40, pattern=r"^[a-zA-Z0-9_-]+$")
    item_id: str = Field(min_length=1, max_length=60, pattern=r"^[a-zA-Z0-9_-]+$")


@router.get("/api/wallet")
def get_wallet(request: Request):
    player = authenticated_player(request)
    with db() as connection:
        row = ensure_wallet(connection, player["id"])
    return {
        "ok": True,
        "player_id": player["id"],
        "username": player["username"],
        "currency": "ATIVA_DIAMONDS",
        "balance": int(row["balance"]),
        "diamonds": int(row["balance"]),
    }


@router.post("/api/wallet/spend")
def spend_wallet(data: SpendInput, request: Request):
    player = authenticated_player(request)
    game_id = data.game_id.strip().lower()
    item_id = data.item_id.strip().lower()
    item = STORE_ITEMS.get((game_id, item_id))
    if not item:
        raise HTTPException(status_code=404, detail="Item não encontrado na loja deste jogo.")

    player_id = player["id"]
    with db() as connection:
        ensure_wallet(connection, player_id)
        # Bloqueio da linha impede dois gastos simultâneos de usar o mesmo saldo.
        wallet = connection.execute(
            "SELECT balance FROM wallet_accounts WHERE player_id = %s FOR UPDATE",
            (player_id,),
        ).fetchone()
        existing = connection.execute(
            "SELECT id FROM player_inventory WHERE player_id = %s AND game_id = %s AND item_id = %s",
            (player_id, game_id, item_id),
        ).fetchone()
        if existing:
            raise HTTPException(status_code=409, detail="Você já possui este item neste jogo.")

        balance = int(wallet["balance"])
        cost = int(item["cost"])
        if balance < cost:
            raise HTTPException(status_code=400, detail=f"Diamantes insuficientes. Você tem {balance} e precisa de {cost}.")

        new_balance = balance - cost
        connection.execute(
            "UPDATE wallet_accounts SET balance = %s, updated_at = %s WHERE player_id = %s",
            (new_balance, now_utc(), player_id),
        )
        connection.execute(
            "INSERT INTO player_inventory (player_id, game_id, item_id, item_name, purchased_at) VALUES (%s, %s, %s, %s, %s)",
            (player_id, game_id, item_id, item["name"], now_utc()),
        )
        connection.execute(
            "INSERT INTO wallet_transactions (player_id, delta, balance_after, reason, game_id, item_id, created_at) VALUES (%s, %s, %s, %s, %s, %s, %s)",
            (player_id, -cost, new_balance, "item_purchase", game_id, item_id, now_utc()),
        )

    return {
        "ok": True,
        "message": "Compra registrada.",
        "game_id": game_id,
        "item_id": item_id,
        "item_name": item["name"],
        "spent": cost,
        "balance": new_balance,
        "diamonds": new_balance,
    }


@router.get("/api/wallet/transactions")
def wallet_transactions(request: Request):
    player = authenticated_player(request)
    with db() as connection:
        rows = connection.execute(
            "SELECT delta, balance_after, reason, game_id, item_id, created_at FROM wallet_transactions WHERE player_id = %s ORDER BY id DESC LIMIT 100",
            (player["id"],),
        ).fetchall()
    return {"items": [dict(row) for row in rows]}


@router.get("/api/wallet/inventory")
def wallet_inventory(request: Request):
    player = authenticated_player(request)
    with db() as connection:
        rows = connection.execute(
            "SELECT game_id, item_id, item_name, purchased_at FROM player_inventory WHERE player_id = %s ORDER BY id DESC LIMIT 200",
            (player["id"],),
        ).fetchall()
    return {"items": [dict(row) for row in rows]}
