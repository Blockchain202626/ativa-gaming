@app.post("/api/register")
def register(data: RegisterInput, response: Response):
    username = data.username.strip()

    if len(username) < 3:
        raise HTTPException(
            status_code=400,
            detail="Nome de usuário muito curto.",
        )

    try:
        with db() as connection:
            row = connection.execute(
                """
                INSERT INTO players
                    (username, password_hash, created_at)
                VALUES (%s, %s, %s)
                RETURNING id
                """,
                (username, hash_password(data.password), now_utc()),
            ).fetchone()

            player_id = row["id"]

    except psycopg.errors.UniqueViolation:
        raise HTTPException(
            status_code=409,
            detail="Esse nome de usuário já está sendo usado.",
        )

    set_player_cookie(response, player_id)

    return {
        "ok": True,
        "player": {
            "id": player_id,
            "username": username,
        },
    }


@app.post("/api/login")
def login(data: LoginInput, response: Response):
    with db() as connection:
        player = connection.execute(
            """
            SELECT id, username, password_hash
            FROM players
            WHERE LOWER(username) = LOWER(%s)
            """,
            (data.username.strip(),),
        ).fetchone()

    if not player or not verify_password(
        data.password,
        player["password_hash"],
    ):
        raise HTTPException(
            status_code=401,
            detail="Usuário ou senha incorretos.",
        )

    set_player_cookie(response, player["id"])

    return {
        "ok": True,
        "player": {
            "id": player["id"],
            "username": player["username"],
        },
    }


